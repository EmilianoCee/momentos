#!/usr/bin/env python3
"""Build the generated parts of the repo from their sources.

    python3 scripts/build.py           write every generated file
    python3 scripts/build.py --check   change nothing; exit 1 if a generated file is out of date

What is generated, and from what:

  index.html (the map-data block)   from map/<folder>.json, curricula/*.json and plans/*.md
  README.md (the tool index)        from the map and each tool's comment header
  curricula/<course>.md             from curricula/<course>.json
  plans/BACKLOG.md                  from plans/*.md and the curricula

Never edit a generated part by hand: edit its source and run this again. Standard library only.
"""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import momentos as m  # noqa: E402


# ------------------------------------------------------------------------------------------ the map

def built_map(problems):
    """The data the map page draws: topics with folder, courses and plan filled in, and links."""
    data = m.load_map(problems)
    curricula = m.load_curricula(problems)
    plans = m.plans_by_topic(m.load_plans(problems))
    order = [c.get("id") for c in m.load_courses(problems)]
    courses = {}
    for cur in curricula:
        for concept in cur.get("concepts", []):
            courses.setdefault(concept.get("topic"), set()).add(cur.get("course"))
    topics = []
    for topic in data["topics"]:
        entry = {k: topic[k] for k in ("id", "title", "folder", "essence", "check", "tools") if topic.get(k)}
        mine = set(topic.get("courses", [])) | courses.get(topic.get("id"), set())
        if mine:
            entry["courses"] = sorted(mine, key=lambda c: (order.index(c) if c in order else len(order), c))
        if topic.get("later"):
            entry["later"] = topic["later"]
        plan = plans.get(topic.get("id"))
        if plan and not topic.get("tools"):
            entry["plan"] = plan["_file"]
            entry["plan_status"] = plan.get("status")
        topics.append(entry)
    links = [{k: link[k] for k in m.LINK_KEYS if k in link} for link in data["links"]]
    return {"topics": topics, "links": links}


def map_block_text(data):
    """One topic and one link per line, so that a diff shows exactly what changed."""
    def rows(items):
        return ",\n".join(json.dumps(item, ensure_ascii=False, separators=(", ", ": ")) for item in items)
    return '\n{"topics": [\n' + rows(data["topics"]) + '\n],\n"links": [\n' + rows(data["links"]) + "\n]}\n"


def build_index(problems):
    text = m.INDEX.read_text(encoding="utf-8")
    if not m.MAP_BLOCK.search(text):
        problems.append('index.html has no <script type="application/json" id="map-data"> block.')
        return {}
    block = map_block_text(built_map(problems))
    return {m.INDEX: m.MAP_BLOCK.sub(lambda hit: hit.group(1) + block + hit.group(3), text, count=1)}


# -------------------------------------------------------------------------------- the tool index

INDEX_BEGIN = "<!-- tool-index:begin (generated by scripts/build.py; do not edit) -->"
INDEX_END = "<!-- tool-index:end -->"


def build_tool_index(problems):
    if not m.README.exists():
        return {}
    text = m.README.read_text(encoding="utf-8")
    a, b = text.find(INDEX_BEGIN), text.find(INDEX_END)
    if a < 0 or b < 0:
        problems.append("README.md has no tool-index markers, so the tool index cannot be generated.")
        return {}
    data = m.load_map([])
    by_tool = {}
    for topic in data["topics"]:
        for tool in topic.get("tools", []):
            by_tool.setdefault(tool, []).append(topic.get("title", ""))
    rows = ["| Tool | Topics on the map | What should click |", "|---|---|---|"]
    for tool in sorted(by_tool):
        path = m.ROOT / tool
        click = ""
        if path.is_file() and path.suffix == ".html":
            click = m.tool_header(path.read_text(encoding="utf-8")).get("Should click", "")
        rows.append(f"| [`{tool}`]({tool}) | {', '.join(by_tool[tool])} | {click.replace('|', '/')} |")
    new = text[:a] + INDEX_BEGIN + "\n" + "\n".join(rows) + "\n" + text[b:]
    return {m.README: new}


# ----------------------------------------------------------------------------------- the curricula

def curriculum_view(cur, titles, plans):
    course = cur.get("course", "?")
    out = [f"# {course}: curriculum", "",
           f"<!-- Generated from {cur['_file']} by scripts/build.py. Do not edit: edit the JSON. -->", ""]
    reg = {c.get("id"): c for c in m.load_courses([])}.get(course, {})
    if reg:
        out += [f"**{reg.get('catalog', course)}: {reg.get('title', '')}.** Tier {cur.get('tier', '?')}. "
                f"Scope taken from {cur.get('scope_term', 'the sources below')}.", ""]
    if cur.get("built_from"):
        out += ["Built from:", ""] + [f"- {line}" for line in cur["built_from"]] + [""]
    if cur.get("notes"):
        out += ["Notes:", ""] + [f"- {line}" for line in cur["notes"]] + [""]
    concepts = cur.get("concepts", [])
    weights = {c.get("topic"): m.concept_weight(c, cur) for c in concepts}
    out += ["## Mastery target", "",
            "L4 on every concept marked 4 below, L3 on the rest. The levels and what counts as evidence are in "
            "[docs/levels.md](../docs/levels.md).", ""]
    out += ["## Outline and coverage", "",
            "Weight is how much a concept is assessed: an exam item counts 1, halved for every 4 years of age; "
            "a homework, discussion, lab or practice item counts 0.5 in the scope term and 0.25 before it. "
            "The identifiers name where it is assessed, so you can find the item in your own copy of the materials.", ""]
    for unit in cur.get("units", []):
        mine = [c for c in concepts if c.get("unit") == unit.get("id")]
        out += [f"### {unit.get('title', unit.get('id'))}", ""]
        if not mine:
            out += ["No concepts listed yet.", ""]
            continue
        out += ["| Concept | Target | Weight | Exams | Assessed in | Flags | Plan |", "|---|---|---|---|---|---|---|"]
        for c in mine:
            tid = c.get("topic")
            w, ew = weights[tid]
            plan = plans.get(tid)
            plan_cell = f"[{plan.get('status')}](../{plan['_file']})" if plan else ""
            assessed = c.get("assessed", [])
            shown = ", ".join(assessed[:8]) + (f", and {len(assessed) - 8} more" if len(assessed) > 8 else "")
            out.append(f"| [{titles.get(tid, tid)}](../index.html#{tid}) | L{c.get('target', '?')} | {w:g} | {ew:g} | "
                       f"{shown} | {', '.join(c.get('flags', []))} | {plan_cell} |")
        out.append("")
    ranked = sorted(concepts, key=lambda c: (-weights[c.get("topic")][0], c.get("topic", "")))
    if ranked:
        out += ["## Priority order", "", "Heaviest first. Study and build tools in this order.", ""]
        out += [f"{n}. {titles.get(c.get('topic'), c.get('topic'))} ({weights[c.get('topic')][0]:g})"
                for n, c in enumerate(ranked, 1)] + [""]
    if cur.get("outline"):
        out += ["## Course outline", ""] + [f"- {line}" for line in cur["outline"]] + [""]
    if cur.get("sources"):
        out += ["## Sources", ""]
        out += [f"- {s.get('title', '')}: <{s.get('url', '')}> (accessed {s.get('accessed', '?')})" if s.get("url")
                else f"- {s.get('title', '')}" for s in cur["sources"]] + [""]
    return "\n".join(out).rstrip() + "\n"


def build_curricula(problems):
    out = {}
    data = m.load_map([])
    titles = {t.get("id"): t.get("title", t.get("id")) for t in data["topics"]}
    plans = m.plans_by_topic(m.load_plans([]))
    for cur in m.load_curricula(problems):
        path = (m.ROOT / cur["_file"]).with_suffix(".md")
        out[path] = curriculum_view(cur, titles, plans)
    return out


# ------------------------------------------------------------------------------------- the backlog

def build_backlog(problems):
    plans = m.load_plans(problems)
    if not m.PLANS_DIR.is_dir():
        return {}
    curricula = m.load_curricula([])
    tier = {}
    weight = {}
    for cur in curricula:
        for c in cur.get("concepts", []):
            tid = c.get("topic")
            tier[tid] = min(tier.get(tid, 9), cur.get("tier", 9))
            weight[tid] = weight.get(tid, 0) + m.concept_weight(c, cur)[0]

    def key(plan):
        topics = plan.get("topics", [])
        return (min([tier.get(t, 9) for t in topics] or [9]), -sum(weight.get(t, 0) for t in topics), plan.get("id", ""))

    out = ["# Backlog", "",
           "<!-- Generated from plans/*.md and curricula/*.json by scripts/build.py. Do not edit. -->", "",
           "The order is fixed by the curricula: course tier first, then how heavily the plan's concepts are assessed.",
           "\"Build the next tool\" means the first row below whose status is `planned`. "
           "\"Write the next plan\" means the first row whose status is `stub`.", "",
           "| # | Plan | Status | Kind | Courses | Weight | Size |", "|---|---|---|---|---|---|---|"]
    for n, plan in enumerate(sorted(plans, key=key), 1):
        w = sum(weight.get(t, 0) for t in plan.get("topics", []))
        name = Path(plan["_file"]).name
        out.append(f"| {n} | [{plan.get('title', plan.get('id'))}]({name}) | {plan.get('status')} | {plan.get('kind')} | "
                   f"{', '.join(plan.get('courses', []))} | {w:g} | {plan.get('size', '')} |")
    covered = {t for plan in plans for t in plan.get("topics", [])}
    data = m.load_map([])
    titles = {t.get("id"): t.get("title") for t in data["topics"]}
    built = {t.get("id") for t in data["topics"] if t.get("tools")}
    missing = []
    for cur in curricula:
        if cur.get("tier", 9) > 3:
            continue
        for c in cur.get("concepts", []):
            tid = c.get("topic")
            if tid not in covered and tid not in built:
                missing.append((cur.get("tier", 9), -m.concept_weight(c, cur)[0], cur.get("course"), tid))
    if missing:
        out += ["", "## Concepts with no plan yet", "",
                "Each needs a plan or a quiz-only plan. Heaviest first within each tier.", "",
                "| Course | Concept | Weight |", "|---|---|---|"]
        seen = set()
        for t, w, course, tid in sorted(missing):
            if tid in seen:
                continue
            seen.add(tid)
            out.append(f"| {course} | {titles.get(tid, tid)} (`{tid}`) | {-w:g} |")
    return {m.PLANS_DIR / "BACKLOG.md": "\n".join(out) + "\n"}


# ------------------------------------------------------------------------------------------- run it

def build_all(problems):
    out = {}
    for step in (build_index, build_tool_index, build_curricula, build_backlog):
        out.update(step(problems))
    return out


def stale(outputs):
    """The generated files whose text on disk differs from what the sources give."""
    return [m.rel(p) for p, text in outputs.items()
            if not p.exists() or p.read_text(encoding="utf-8") != text]


def main():
    check = "--check" in sys.argv[1:]
    problems = []
    outputs = build_all(problems)
    for message in problems:
        print("  ERROR    " + message)
    if problems:
        return 1
    old = stale(outputs)
    if check:
        for name in old:
            print(f"  ERROR    {name} is out of date. Run: python3 scripts/build.py")
        if not old:
            print(f"Generated files are up to date ({len(outputs)} checked).")
        return 1 if old else 0
    for path, text in outputs.items():
        if m.rel(path) in old:
            path.write_text(text, encoding="utf-8")
            print("  wrote    " + m.rel(path))
    if not old:
        print(f"Nothing to do: {len(outputs)} generated files were already up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
